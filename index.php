        }

        function updateContent() {
            const data = content[currentLang];
            
            // Update text elements with data-key attribute
            document.querySelectorAll('[data-key]').forEach(el => {
                const keys = el.getAttribute('data-key').split('.');
                let val = data;
                keys.forEach(k => val = val[k]);
                el.innerText = val;
            });

            // Update placeholders
            document.getElementById('input-name').placeholder = data.form.ph_name;
            document.getElementById('input-email').placeholder = data.form.ph_email;
            document.getElementById('input-phone').placeholder = data.form.ph_phone;
            document.getElementById('input-message').placeholder = data.form.placeholder;

            // Update toggle styles
            const huLabel = document.getElementById('lang-hu');
            const enLabel = document.getElementById('lang-en');
            const mobLabel = document.getElementById('mobile-lang-btn');
            
            if (currentLang === 'hu') {
                huLabel.classList.add('font-extrabold'); huLabel.classList.remove('opacity-50');
                enLabel.classList.remove('font-extrabold'); enLabel.classList.add('opacity-50');
                mobLabel.innerText = "HU";
