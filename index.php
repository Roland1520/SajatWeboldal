        window.addEventListener('scroll', () => {
            const navbar = document.getElementById('navbar');
            if (window.scrollY > 50) {
                navbar.classList.remove('mix-blend-difference', 'py-6');
                navbar.classList.add('bg-[#0a0a0a]/80', 'backdrop-blur-md', 'py-4', 'border-b', 'border-white/5');
            } else {
                navbar.classList.add('mix-blend-difference', 'py-6');
                navbar.classList.remove('bg-[#0a0a0a]/80', 'backdrop-blur-md', 'py-4', 'border-b', 'border-white/5');
            }
        });

